/*
|--------------------------------------------------------------------------
| GET JWT TOKEN
|--------------------------------------------------------------------------
|
| Retrieves the JWT token stored in localStorage.
|
|--------------------------------------------------------------------------
*/

function getToken() {

    return localStorage.getItem(
        'token'
    );

}


/*
|--------------------------------------------------------------------------
| LOGOUT
|--------------------------------------------------------------------------
|
| Removes authentication information and redirects the user to login.
|
|--------------------------------------------------------------------------
*/

function logout() {

    /*
    |--------------------------------------------------------------------------
    | REMOVE JWT TOKEN
    |--------------------------------------------------------------------------
    */

    localStorage.removeItem(
        'token'
    );


    /*
    |--------------------------------------------------------------------------
    | REMOVE STORED USER
    |--------------------------------------------------------------------------
    */

    localStorage.removeItem(
        'user'
    );


    /*
    |--------------------------------------------------------------------------
    | REDIRECT TO LOGIN
    |--------------------------------------------------------------------------
    */

    window.location.href =
        '/login.html';

}


/*
|--------------------------------------------------------------------------
| API REQUEST HELPER
|--------------------------------------------------------------------------
|
| Used by authenticated pages.
|
| Automatically sends:
|
| Authorization: Bearer JWT
|
|--------------------------------------------------------------------------
*/

async function api(
    url,
    options = {}
) {

    /*
    |--------------------------------------------------------------------------
    | COPY OPTIONS
    |--------------------------------------------------------------------------
    |
    | Do not directly modify the object supplied by the caller.
    |
    |--------------------------------------------------------------------------
    */

    const config = {
        ...options
    };


    /*
    |--------------------------------------------------------------------------
    | CREATE HEADERS
    |--------------------------------------------------------------------------
    */

    config.headers = {

        ...(options.headers || {})

    };


    /*
    |--------------------------------------------------------------------------
    | GET JWT TOKEN
    |--------------------------------------------------------------------------
    */

    const token =
        getToken();


    /*
    |--------------------------------------------------------------------------
    | ADD AUTHORIZATION HEADER
    |--------------------------------------------------------------------------
    */

    if (token) {

        config.headers.Authorization =
            `Bearer ${token}`;

    }


    /*
    |--------------------------------------------------------------------------
    | SEND REQUEST
    |--------------------------------------------------------------------------
    */

    let response;

    try {

        response =
            await fetch(
                url,
                config
            );

    } catch (error) {

        /*
        |--------------------------------------------------------------------------
        | NETWORK ERROR
        |--------------------------------------------------------------------------
        */

        console.error(
            'API NETWORK ERROR:',
            error
        );

        throw new Error(
            'Unable to connect to the server.'
        );

    }


    /*
    |--------------------------------------------------------------------------
    | READ RESPONSE AS TEXT FIRST
    |--------------------------------------------------------------------------
    |
    | This is very important.
    |
    | Calling response.json() directly can produce:
    |
    | Unexpected token '<'
    |
    | when Express returns HTML such as a 404 page.
    |
    |--------------------------------------------------------------------------
    */

    const text =
        await response.text();


    /*
    |--------------------------------------------------------------------------
    | PREPARE JSON DATA
    |--------------------------------------------------------------------------
    */

    let data;


    /*
    |--------------------------------------------------------------------------
    | PARSE JSON
    |--------------------------------------------------------------------------
    */

    if (text) {

        try {

            data =
                JSON.parse(text);

        } catch (error) {

            /*
            |--------------------------------------------------------------------------
            | SERVER RETURNED NON-JSON
            |--------------------------------------------------------------------------
            */

            console.error(
                'INVALID API RESPONSE:',
                text
            );


            throw new Error(

                `Server returned an invalid response. HTTP ${response.status}`

            );

        }

    } else {

        /*
        |--------------------------------------------------------------------------
        | EMPTY RESPONSE
        |--------------------------------------------------------------------------
        */

        data = {

            success:
                response.ok

        };

    }


    /*
    |--------------------------------------------------------------------------
    | CHECK HTTP STATUS
    |--------------------------------------------------------------------------
    */

    if (!response.ok) {

        /*
        |--------------------------------------------------------------------------
        | AUTOMATICALLY HANDLE UNAUTHORIZED
        |--------------------------------------------------------------------------
        */

        if (
            response.status === 401
        ) {

            localStorage.removeItem(
                'token'
            );

            localStorage.removeItem(
                'user'
            );

        }


        /*
        |--------------------------------------------------------------------------
        | THROW SERVER MESSAGE
        |--------------------------------------------------------------------------
        */

        throw new Error(

            data.message ||
            `HTTP ${response.status}`

        );

    }


    /*
    |--------------------------------------------------------------------------
    | CHECK API SUCCESS FLAG
    |--------------------------------------------------------------------------
    */

    if (
        data.success === false
    ) {

        throw new Error(

            data.message ||
            'Request failed'

        );

    }


    /*
    |--------------------------------------------------------------------------
    | RETURN JSON
    |--------------------------------------------------------------------------
    */

    return data;

}